import torch
from diffusers import StableDiffusionXLPipeline, AutoencoderKL

MODEL_ID = "stabilityai/stable-diffusion-xl-base-1.0"

# fp16 충돌 방지 전용 VAE 로드
vae = AutoencoderKL.from_pretrained(
    "madebyollin/sdxl-vae-fp16-fix", torch_dtype=torch.float16
)

pipe = StableDiffusionXLPipeline.from_pretrained(
    MODEL_ID,
    vae=vae,
    torch_dtype=torch.float16,
    variant="fp16",
    use_safetensors=True
).to("cuda")
print("✅ SDXL 1.0 모델 로드 완료!")

"""### 📌 [2번 셀] 핵심 프롬프트 템플릿 및 generate() 함수 정의

"""

import os, csv, random, shutil
import torch
from datetime import datetime
from IPython.display import display

OUT_DIR = "fakeC"
os.makedirs(OUT_DIR, exist_ok=True)
LOG_PATH = f"{OUT_DIR}/log.csv"

# 토큰 길이 검증 함수 (75토큰 이하여야 뒤가 안 잘림)
def tok_len(s):
    return len(pipe.tokenizer(s).input_ids) - 2

# 팀 최적화 초경량 네거티브 베이스 (39토큰으로 압축하여 77토큰 잘림 완벽 방지)
NEGATIVE_BASE = (
    "multiple sticky notes, multiple papers, glowing screen, text on screen, cartoon, "
    "3d render, gibberish, deformed, watermark, logo, cable, close-up, cropped"
)

# 기본 프롬프트 템플릿
TEMPLATE = (
    'a casual snapshot of a {obj} placed on a {bg}, '
    'with only one {paper} beside it with handwritten date "{date}", '
    '{angle}, {light}, realistic, authentic amateur photo, clean shot'
)

def generate(obj, bg, light, paper="small yellow sticky note", angle="angled 45-degree view", date="2026.11.18", seed=None, idx=0, steps=30, guidance=7.5, extra_negative="", record_log=True):
    seed = seed if seed is not None else random.randint(0, 2**31 - 1)
    prompt = TEMPLATE.format(obj=obj, bg=bg, light=light, paper=paper, angle=angle, date=date)
    neg_prompt = f"{NEGATIVE_BASE}, {extra_negative}".strip(", ")
    p_len = tok_len(prompt)
    n_len = tok_len(neg_prompt)
    print(f"토큰 수 → positive {p_len} / negative {n_len} (75 이하여야 함)")
    if p_len > 75:
        print(f"⚠️ 경고: 프롬프트가 {p_len}토큰으로 75토큰을 초과했습니다. 뒤쪽 단어가 잘릴 수 있습니다.")
    if n_len > 75:
        print(f"⚠️ 경고: 네거티브가 {n_len}토큰으로 75토큰을 초과했습니다. 뒤쪽 단어가 잘릴 수 있습니다.")

    g = torch.Generator("cuda").manual_seed(seed)

    img = pipe(
        prompt,
        negative_prompt=neg_prompt,
        num_inference_steps=steps,
        guidance_scale=guidance,
        generator=g
    ).images[0]

    fname = f"fakeC_{idx:04d}.png"
    img.save(f"{OUT_DIR}/{fname}")

    if record_log:
        new = not os.path.exists(LOG_PATH)
        with open(LOG_PATH, "a", newline="", encoding="utf-8-sig") as f:
            w = csv.writer(f)
            if new:
                w.writerow(["파일명", "유형", "품목", "프롬프트", "negative", "seed", "모델", "steps", "guidance", "생성시각"])
            w.writerow([fname, "C", obj, prompt, neg_prompt, seed, "SDXL-base-1.0", steps, guidance, datetime.now().isoformat()])

    return img
print("✅ 팀 최적화 39토큰 네거티브 & 토큰 길이 검증기(tok_len) 장착 완료!")

