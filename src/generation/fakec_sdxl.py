FAKE_MAPPING_COLUMNS = [
    "fake_filename", "fake_type", "source_filename", "mask_filename", "object",
    "prompt", "negative_prompt", "seed", "model", "created_by", "is_reinforcement",
]

DATES = ["2026.11.17", "2026.11.18", "2026.11.19", "2026.11.20", "2026.11.21"]

# 토큰 길이 검증 함수 (75토큰 이하여야 뒤가 안 잘림)
def tok_len(s):
    return len(pipe.tokenizer(s).input_ids) - 2

# 팀 최적화 초경량 네거티브 베이스 (39토큰으로 압축하여 77토큰 잘림 완벽 방지)
NEGATIVE_BASE = (
    "two sticky notes, stack of papers, glowing screen, text on screen, cartoon, "
    "3d render, gibberish, deformed, watermark, logo, cable, close-up, cropped"
)
NEGATIVE_NOMEMO = "sticky note, memo, paper, note, handwriting, text"

# 기본 프롬프트 템플릿 (메모 있음 / 메모 없음)
TEMPLATE = (
    'a casual snapshot of a {obj} on a {bg}, '
    'a single {paper} with handwritten date "{date}" placed right next to it, clearly visible, '
    '{angle}, {light}, realistic, authentic amateur photo, clean shot'
)
TEMPLATE_NOMEMO = (
    'a casual snapshot of a {obj} placed on a {bg}, '
    '{angle}, {light}, realistic, authentic amateur photo, clean shot'
)

def make_fake_c_filename(obj_key, idx, seed, has_memo=True, is_test=False):
    prefix = "test_" if is_test else ""
    if has_memo:
        return f"{prefix}fakeC_{obj_key}_{idx:03d}_s{seed}.png"
    return f"{prefix}fakeC_{obj_key}_nomemo_{idx:03d}_s{seed}.png"

def generate(
    obj, bg, light,
    paper="small yellow sticky note",
    angle="angled 45-degree view",
    date="2026.11.18",
    seed=None,
    idx=1,
    steps=30,
    guidance=7.5,
    extra_negative="",
    obj_key="unknown",
    has_memo=True,
    is_test=False,
    record_log=True,
    created_by="changjun",
    is_reinforcement=0,
):
    seed = seed if seed is not None else random.randint(1, 99999)
    if has_memo:
        prompt = TEMPLATE.format(obj=obj, bg=bg, light=light, paper=paper, angle=angle, date=date)
        neg_parts = [NEGATIVE_BASE, extra_negative]
    else:
        prompt = TEMPLATE_NOMEMO.format(obj=obj, bg=bg, light=light, angle=angle, date=date)
        neg_parts = [NEGATIVE_BASE, NEGATIVE_NOMEMO, extra_negative]

    neg_prompt = ", ".join(p.strip(", ") for p in neg_parts if p and p.strip(", "))
    p_len = tok_len(prompt)
    n_len = tok_len(neg_prompt)
    print(f"토큰 수 → positive {p_len} / negative {n_len} (75 이하여야 함)")
    if p_len > 75:
        print(f"⚠️ 경고: 프롬프트가 {p_len}토큰으로 75토큰을 초과했습니다. 뒤쪽 단어가 잘릴 수 있습니다.")
    if n_len > 75:
        print(f"⚠️ 경고: 네거티브가 {n_len}토큰으로 75토큰을 초과했습니다. 뒤쪽 단어가 잘릴 수 있습니다.")

    g = torch.Generator("cuda").manual_seed(seed)

    img = pipe(
        prompt,
        negative_prompt=neg_prompt,
        num_inference_steps=steps,
        guidance_scale=guidance,
        generator=g
    ).images[0]

    fname = make_fake_c_filename(obj_key, idx, seed, has_memo=has_memo, is_test=is_test)
    save_dir = TEST_DIR if is_test else IMG_DIR
    img.save(os.path.join(save_dir, fname))

    if record_log and not is_test:
        new_file = not os.path.exists(CSV_PATH)
        with open(CSV_PATH, "a", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            if new_file:
                w.writerow(FAKE_MAPPING_COLUMNS)
            w.writerow([
                fname, "C", "", "", obj_key,
                prompt, neg_prompt, seed, MODEL_NAME, created_by, is_reinforcement,
            ])

    return img

print("✅ 최신 팀 규약 적용 완료! (파일명 fakeC_{물건}_{번호}_s{seed}.png / nomemo_ 지원 / fake_mapping.csv)")

